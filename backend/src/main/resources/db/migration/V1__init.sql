-- 업로드된 Swagger 명세
CREATE TABLE api_spec (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title          VARCHAR(255) NOT NULL,
  version        VARCHAR(100),
  source_type    VARCHAR(20)  NOT NULL,
  content        CLOB         NOT NULL,
  content_hash   VARCHAR(64)  NOT NULL,
  endpoint_count INT          NOT NULL,
  schema_count   INT          NOT NULL,
  status         VARCHAR(30)  NOT NULL,
  created_at     TIMESTAMP    NOT NULL
);

-- AI 분석 결과
CREATE TABLE analysis_result (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spec_id     BIGINT    NOT NULL REFERENCES api_spec(id) ON DELETE CASCADE,
  result_json CLOB      NOT NULL,
  created_at  TIMESTAMP NOT NULL
);

-- 생성된 RestClient 소스
CREATE TABLE generated_client (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spec_id     BIGINT    NOT NULL REFERENCES api_spec(id) ON DELETE CASCADE,
  files_json  CLOB      NOT NULL,
  compiled    BOOLEAN   NOT NULL,
  compile_log CLOB,
  created_at  TIMESTAMP NOT NULL
);

-- 엔드포인트별 샘플 데이터
CREATE TABLE sample_data (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spec_id        BIGINT       NOT NULL REFERENCES api_spec(id) ON DELETE CASCADE,
  operation_id   VARCHAR(255) NOT NULL,
  request_json   CLOB,
  valid          BOOLEAN      NOT NULL,
  validation_log CLOB,
  updated_at     TIMESTAMP    NOT NULL,
  CONSTRAINT uq_sample UNIQUE (spec_id, operation_id)
);

-- 통신 테스트 실행 및 케이스 결과
CREATE TABLE test_run (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spec_id    BIGINT       NOT NULL REFERENCES api_spec(id) ON DELETE CASCADE,
  base_url   VARCHAR(500) NOT NULL,
  status     VARCHAR(20)  NOT NULL,
  total      INT          NOT NULL,
  passed     INT          NOT NULL,
  created_at TIMESTAMP    NOT NULL
);

CREATE TABLE test_case_result (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id         BIGINT       NOT NULL REFERENCES test_run(id) ON DELETE CASCADE,
  operation_id   VARCHAR(255) NOT NULL,
  method         VARCHAR(10)  NOT NULL,
  path           VARCHAR(500) NOT NULL,
  status_code    INT,
  elapsed_ms     BIGINT,
  schema_valid   BOOLEAN,
  passed         BOOLEAN      NOT NULL,
  request_json   CLOB,
  response_json  CLOB,
  failure_reason CLOB
);
